// Ships the library's fonts and writes dist/fonts.css.
//
//   node scripts/build-fonts.mjs
//
// Three private families, so a font the person has installed can never take over:
//   "OrgTik Arabic"     IBM Plex Sans Arabic (D-010), Arabic subset only (unicode-range), 400–700.
//                       Latin text falls through to the next family in the stack.
//   "OrgTik Montserrat" Montserrat variable, latin + latin-ext (FR œ, DE ẞ), for headings.
//   "OrgTik Plex"       IBM Plex Sans, latin + latin-ext, for all Latin UI text.
// All are OFL-1.1 (from @fontsource). The files are copied into fonts/ and published with the
// package; fonts.css points at them relatively, so any bundler resolves them.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "package.json"));
const plex = path.dirname(require.resolve("@fontsource/ibm-plex-sans-arabic/package.json"));
const mont = path.dirname(require.resolve("@fontsource-variable/montserrat/package.json"));
const latin = path.dirname(require.resolve("@fontsource/ibm-plex-sans/package.json"));
const fontsDir = path.join(root, "fonts");
fs.mkdirSync(fontsDir, { recursive: true });

// The unicode-range fontsource gives a subset, read from its CSS so it stays exact.
function rangeOf(cssFile, fileName) {
  const css = fs.readFileSync(cssFile, "utf8");
  const at = css.indexOf(fileName);
  const m = css.slice(at).match(/unicode-range:\s*([^;]+);/);
  if (at < 0 || !m) throw new Error(`no unicode-range for ${fileName} in ${cssFile}`);
  return m[1].trim();
}

const faces = [];
for (const weight of [400, 500, 600, 700]) {
  const file = `ibm-plex-sans-arabic-arabic-${weight}-normal.woff2`;
  fs.copyFileSync(path.join(plex, "files", file), path.join(fontsDir, file));
  faces.push({ family: "OrgTik Arabic", file, weight: String(weight), range: rangeOf(path.join(plex, `${weight}.css`), file) });
}
for (const subset of ["latin-ext", "latin"]) {
  const file = `montserrat-${subset}-wght-normal.woff2`;
  fs.copyFileSync(path.join(mont, "files", file), path.join(fontsDir, file));
  faces.push({ family: "OrgTik Montserrat", file, weight: "100 900", range: rangeOf(path.join(mont, "index.css"), file) });
}
for (const weight of [400, 500, 600, 700]) for (const subset of ["latin-ext", "latin"]) {
  const file = `ibm-plex-sans-${subset}-${weight}-normal.woff2`;
  fs.copyFileSync(path.join(latin, "files", file), path.join(fontsDir, file));
  faces.push({ family: "OrgTik Plex", file, weight: String(weight), range: rangeOf(path.join(latin, `${weight}.css`), file) });
}

// OFL-1.1 requires the licence to travel with the fonts.
fs.copyFileSync(path.join(plex, "LICENSE"), path.join(fontsDir, "OFL-IBM-Plex-Sans-Arabic.txt"));
fs.copyFileSync(path.join(mont, "LICENSE"), path.join(fontsDir, "OFL-Montserrat.txt"));
fs.copyFileSync(path.join(latin, "LICENSE"), path.join(fontsDir, "OFL-IBM-Plex-Sans.txt"));

const css =
  "/* Generated by scripts/build-fonts.mjs. Don't edit by hand. Fonts: OFL-1.1. */\n" +
  faces
    .map(
      (f) => `@font-face {
  font-family: "${f.family}";
  font-style: normal;
  font-weight: ${f.weight};
  font-display: swap;
  src: url("../fonts/${f.file}") format("woff2");
  unicode-range: ${f.range};
}`,
    )
    .join("\n");
fs.mkdirSync(path.join(root, "dist"), { recursive: true });
fs.writeFileSync(path.join(root, "dist", "fonts.css"), css + "\n");
const kb = faces.reduce((n, f) => n + fs.statSync(path.join(fontsDir, f.file)).size, 0) / 1024;
console.log(`fonts: ${faces.length} faces, ${Math.round(kb)} KB -> fonts/, dist/fonts.css`);
