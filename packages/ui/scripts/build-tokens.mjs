// Builds the library's tokens from tokens/*.json (W3C design-token shapes).
//
//   node scripts/build-tokens.mjs
//
// Writes, into dist/:
//   tokens.css   --ot-* custom properties: primitives on :root; the semantic set for
//                [data-theme="light"] (also the default, D-023) and [data-theme="dark"]; Arabic
//                type adjustments under :lang(ar); 1ms durations under reduced motion
//   theme.css    Tailwind v4 `@theme inline` mapping utilities (bg-raised, text-fg-muted,
//                rounded-pill, text-body …) onto those properties
// and src/tokens.ts, the same values for code (charts, canvas, tests).
//
// Semantic colours that equal a primitive are written as var(--ot-color-…), so the aliasing
// survives into CSS and, later, into the Figma variables.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = JSON.parse(fs.readFileSync(path.join(root, "tokens", "color-and-scale.json"), "utf8"));
const scale = JSON.parse(fs.readFileSync(path.join(root, "tokens", "type-and-size.json"), "utf8"));
const elevation = JSON.parse(fs.readFileSync(path.join(root, "tokens", "elevation.json"), "utf8"));
const out = path.join(root, "dist");
fs.mkdirSync(out, { recursive: true });

const value = (t) => t.$value;
const header = "/* Generated by scripts/build-tokens.mjs from tokens/*.json. Don't edit by hand. */\n";

// Primitives.
const primitives = {};
for (const [ramp, steps] of Object.entries(src.color)) for (const [step, t] of Object.entries(steps)) primitives[`--ot-color-${ramp}-${step}`] = value(t).toUpperCase();
const byHex = new Map(Object.entries(primitives).map(([k, v]) => [v, k]));
const ref = (hex) => (byHex.has(hex.toUpperCase()) ? `var(${byHex.get(hex.toUpperCase())})` : hex);

const scalar = {};
for (const [k, t] of Object.entries(src.radius)) scalar[`--ot-radius-${k}`] = value(t);
for (const [k, t] of Object.entries(src.duration)) scalar[`--ot-duration-${k}`] = value(t);
for (const [k, t] of Object.entries(src.easing)) scalar[`--ot-ease-${k}`] = `cubic-bezier(${value(t).join(", ")})`;
const family = (list) => list.map((f) => (/\s/.test(f) && !/^(sans-serif|serif|monospace)$/.test(f) ? `"${f}"` : f)).join(", ");
for (const [k, t] of Object.entries(src.font)) scalar[`--ot-font-${k}`] = family(value(t));
for (const [role, t] of Object.entries(scale.type)) {
  scalar[`--ot-type-${role}-size`] = t.size;
  scalar[`--ot-type-${role}-line`] = String(t.line);
  scalar[`--ot-type-${role}-weight`] = String(t.weight);
  scalar[`--ot-type-${role}-tracking`] = t.tracking;
}
for (const [k, v] of Object.entries(scale.control)) scalar[`--ot-control-${k}`] = v;
for (const group of ["space", "layout", "zIndex"]) for (const [k, t] of Object.entries(src[group] ?? {})) scalar[`--ot-${group === "zIndex" ? "z" : group}-${k}`] = value(t);
scalar["--ot-row-height"] = src.density.comfortable.row;
scalar["--ot-density-control"] = src.density.comfortable.control;

// Semantic sets.
const semantic = { light: {}, dark: {} };
for (const theme of ["light", "dark"]) for (const [name, t] of Object.entries(src.semantic[theme])) semantic[theme][`--ot-${name}`] = ref(value(t));
for (const theme of ["light", "dark"]) for (const [name, t] of Object.entries(elevation[theme])) semantic[theme][`--ot-${name}`] = value(t);

// Interaction colours, derived so they follow each theme: a fill mixes toward the text colour.
const derived = {
  "--ot-action-primary-hover": "color-mix(in oklab, var(--ot-action-primary-bg), var(--ot-action-primary-fg) 18%)",
  "--ot-action-brand-hover": "color-mix(in oklab, var(--ot-action-brand-bg), var(--ot-action-brand-fg) 18%)",
  "--ot-danger-solid-hover": "color-mix(in oklab, var(--ot-danger-solid), var(--ot-fg) 14%)",
  "--ot-hover": "color-mix(in oklab, var(--ot-fg) 7%, transparent)",
  "--ot-pressed": "color-mix(in oklab, var(--ot-fg) 12%, transparent)",
  // The brand tone's quiet fill (badges, selected rows): the brand text colour, faint over a raised surface.
  "--ot-brand-subtle": "color-mix(in oklab, var(--ot-fg-brand) 12%, var(--ot-bg-raised))",
};

const block = (sel, vars, extra = "") => `${sel} {\n${extra}${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;
const arabic = {};
for (const [role, t] of Object.entries(scale.type)) {
  arabic[`--ot-type-${role}-tracking`] = "0";
  arabic[`--ot-type-${role}-line`] = String(Math.round(t.line * scale.arabic.lineScale * 100) / 100);
}
const reduced = Object.fromEntries(Object.keys(src.duration).map((k) => [`--ot-duration-${k}`, "1ms"]));

const css =
  header +
  block(":root", { ...primitives, ...scalar }) +
  "\n" +
  block(':root,\n[data-theme="light"]', semantic.light, "  color-scheme: light;\n") +
  "\n" +
  block('[data-theme="dark"]', semantic.dark, "  color-scheme: dark;\n") +
  "\n" +
  // Also on every [data-theme] element: a custom property that reads others resolves where it is
  // declared, so a scoped dark area (a ThemeScope, a Storybook frame) must recompute these.
  block(":root,\n[data-theme]", derived) +
  block('[data-density="compact"]', { "--ot-row-height": src.density.compact.row, "--ot-density-control": src.density.compact.control }) +
  block('[data-density="comfortable"]', { "--ot-row-height": src.density.comfortable.row, "--ot-density-control": src.density.comfortable.control }) +
  "\n/* Arabic: no letter-spacing, taller lines. */\n" +
  block(":lang(ar)", arabic) +
  "\n@media (prefers-reduced-motion: reduce) {\n" +
  block("  :root", reduced).replace(/^/gm, "  ").trimEnd() +
  "\n}\n";
fs.writeFileSync(path.join(out, "tokens.css"), css);

// Tailwind names for the semantic colours: the role, without the bg- prefix; text on a fill is on-<fill>.
const twName = (name) =>
  name
    .replace(/^bg-/, "")
    .replace(/^action-(\w+)-bg$/, "action-$1")
    .replace(/^action-(\w+)-fg$/, "on-action-$1")
    .replace(/^(\w+)-on-solid$/, "on-$1-solid")
    .replace(/^(success|warning|danger|info)-fg$/, "$1");
const theme = [];
for (const name of Object.keys(src.semantic.light)) theme.push(`  --color-${twName(name)}: var(--ot-${name});`);
for (const k of ["action-primary-hover", "action-brand-hover", "danger-solid-hover", "hover", "pressed", "brand-subtle"]) theme.push(`  --color-${k}: var(--ot-${k});`);
theme.push("  --color-scrim: var(--ot-scrim);");
for (const k of ["xs", "sm", "md", "lg", "xl", "lit", "contact", "raised", "overlay"]) theme.push(`  --shadow-${k}: var(--ot-shadow-${k});`);
for (const k of Object.keys(src.space ?? {})) theme.push(`  --spacing-ot-${k}: var(--ot-space-${k});`);
for (const k of Object.keys(src.radius)) theme.push(`  --radius-${k}: var(--ot-radius-${k});`);
for (const k of Object.keys(src.font)) theme.push(`  --font-${k}: var(--ot-font-${k});`);
for (const k of Object.keys(src.easing)) theme.push(`  --ease-ot-${k}: var(--ot-ease-${k});`);
for (const role of Object.keys(scale.type)) {
  theme.push(`  --text-${role}: var(--ot-type-${role}-size);`);
  theme.push(`  --text-${role}--line-height: var(--ot-type-${role}-line);`);
  theme.push(`  --text-${role}--letter-spacing: var(--ot-type-${role}-tracking);`);
  theme.push(`  --text-${role}--font-weight: var(--ot-type-${role}-weight);`);
}
for (const k of Object.keys(scale.control)) theme.push(`  --spacing-control-${k}: var(--ot-control-${k});`);
fs.writeFileSync(path.join(out, "theme.css"), header + "@theme inline {\n" + theme.join("\n") + "\n}\n");

// For code.
const data = {
  color: Object.fromEntries(Object.entries(src.color).map(([r, s]) => [r, Object.fromEntries(Object.entries(s).map(([k, t]) => [k, value(t)]))])),
  semantic: Object.fromEntries(["light", "dark"].map((th) => [th, Object.fromEntries(Object.entries(src.semantic[th]).map(([k, t]) => [k, value(t)]))])),
  radius: Object.fromEntries(Object.entries(src.radius).map(([k, t]) => [k, value(t)])),
  duration: Object.fromEntries(Object.entries(src.duration).map(([k, t]) => [k, value(t)])),
  type: scale.type,
  control: scale.control,
  space: Object.fromEntries(Object.entries(src.space).map(([k, t]) => [k, value(t)])),
  layout: Object.fromEntries(Object.entries(src.layout).map(([k, t]) => [k, value(t)])),
  zIndex: Object.fromEntries(Object.entries(src.zIndex).map(([k, t]) => [k, value(t)])),
  density: src.density,
  elevation,
};
// A TypeScript module, so the compile emits tokens.js and an exact tokens.d.ts. Written only when
// it changes: it is a tracked source file, and on Windows Turborepo holds its inputs mapped while
// the build runs, so rewriting it unchanged fails there.
const tokensTs = path.join(root, "src", "tokens.ts");
const tokensSource = `// Generated by scripts/build-tokens.mjs from tokens/*.json. Don't edit by hand.
export const tokens = ${JSON.stringify(data, null, 2)} as const;
`;
if (!fs.existsSync(tokensTs) || fs.readFileSync(tokensTs, "utf8") !== tokensSource) fs.writeFileSync(tokensTs, tokensSource);

console.log(`tokens: ${Object.keys(primitives).length} primitives, ${Object.keys(semantic.light).length} semantic × 2 themes, ${Object.keys(scale.type).length} type roles -> dist/`);
