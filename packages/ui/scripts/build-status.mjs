// Builds the library's status table from the program's unified status matrix (G0-approved).
//
//   node scripts/build-status.mjs [path/to/status-matrix.csv]
//
// Default source: ../../../orgtik-program/status-matrix/status-matrix.csv (the sibling program
// repo). Writes src/status/matrix.ts (labels in 5 languages, the customer-facing labels where a
// state reads differently to customers (D-027), tone, icon, next states) and src/status/icons.ts
// (only the Phosphor icons the matrix uses). Both are committed, so consumers never need the CSV.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.resolve(process.argv[2] ?? path.join(root, "..", "..", "..", "orgtik-program", "status-matrix", "status-matrix.csv"));

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((f) => f !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}

const rows = parseCsv(fs.readFileSync(source, "utf8").replace(/^﻿/, ""));
const LOCALES = ["en", "ar", "de", "fr", "it"];
const TONES = new Set(["brand", "danger", "info", "neutral", "success", "warning"]);
const table = {};
const icons = new Set();
for (const r of rows) {
  if (!TONES.has(r.tone)) throw new Error(`${r.entity}.${r.state_key}: unknown tone "${r.tone}"`);
  const entry = {
    tone: r.tone,
    icon: r.icon || null,
    label: Object.fromEntries(LOCALES.map((l) => [l, r[`label_${l}`] || r.label_en])),
    next: r.next_states ? r.next_states.split(",").map((s) => s.trim()).filter(Boolean) : [],
  };
  if (r.customer_label_en) entry.customerLabel = Object.fromEntries(LOCALES.map((l) => [l, r[`customer_label_${l}`] || r.customer_label_en]));
  if (r.icon) icons.add(r.icon);
  (table[r.entity] ??= {})[r.state_key] = entry;
}

const outDir = path.join(root, "src", "status");
fs.mkdirSync(outDir, { recursive: true });
const header = `// Generated by scripts/build-status.mjs from the unified status matrix. Don't edit by hand.\n`;
fs.writeFileSync(
  path.join(outDir, "matrix.ts"),
  `${header}export const STATUS_MATRIX = ${JSON.stringify(table, null, 2)} as const;\n\nexport type StatusEntity = keyof typeof STATUS_MATRIX;\nexport type StatusState<E extends StatusEntity> = keyof (typeof STATUS_MATRIX)[E] & string;\n`,
);
const names = [...icons].sort();
fs.writeFileSync(
  path.join(outDir, "icons.ts"),
  `${header}import { ${names.join(", ")}, type Icon } from "@phosphor-icons/react";\n\nexport const STATUS_ICONS: Record<string, Icon> = { ${names.join(", ")} };\n`,
);
console.log(`status: ${rows.length} states in ${Object.keys(table).length} entities, ${names.length} icons -> src/status/`);
