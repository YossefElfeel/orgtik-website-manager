// Copies the OrgTik mark and wordmark from the website's logo files into src/brand/logo.ts:
// path data and viewBox only (the files' C2PA metadata and fills are dropped), so the Logo
// component draws them in currentColor and follows the theme.
//
//   node scripts/build-logo.mjs [path/to/website/public/assets/logo]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.resolve(process.argv[2] ?? path.join(root, "..", "..", "..", "orgtik-website", "landing-directions", "public", "assets", "logo"));

function read(file) {
  const svg = fs.readFileSync(path.join(dir, file), "utf8").replace(/<metadata>[\s\S]*?<\/metadata>/g, "");
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1].replace(/\s+/g, " ").trim());
  const polygons = [...svg.matchAll(/<polygon[^>]*\spoints="([^"]+)"/g)].map((m) => `M${m[1].trim().replace(/\s+/g, " ")}Z`);
  return { viewBox, paths: [...paths, ...polygons] };
}

// The gradient the colour lockup gives the mark.
const color = fs.readFileSync(path.join(dir, "orgtik-lockup-color.svg"), "utf8");
const grad = color.match(/<linearGradient id="SVGID_1_"[^>]*x1="([\d.]+)" y1="([\d.]+)" x2="([\d.]+)" y2="([\d.]+)">([\s\S]*?)<\/linearGradient>/);
const stops = [...grad[5].matchAll(/offset="([\d.]+)"[^>]*stop-color:(#[0-9A-Fa-f]{6})/g)].map((m) => ({ offset: Number(m[1]), color: m[2] }));

const data = {
  mark: read("orgtik-mark-black.svg"),
  wordmark: read("orgtik-wordmark-black.svg"),
  gradient: { x1: Number(grad[1]), y1: Number(grad[2]), x2: Number(grad[3]), y2: Number(grad[4]), stops },
};
fs.mkdirSync(path.join(root, "src", "brand"), { recursive: true });
fs.writeFileSync(
  path.join(root, "src", "brand", "logo-data.ts"),
  `// Generated by scripts/build-logo.mjs from the website's logo files. Don't edit by hand.\nexport const LOGO = ${JSON.stringify(data, null, 2)} as const;\n`,
);
console.log(`logo: mark ${data.mark.paths.length} paths, wordmark ${data.wordmark.paths.length} paths, ${stops.length} gradient stops`);
